export function noteMacros(profile: NoteMathProfile): Record<string, string> {
  // New object per document prevents definitions from leaking into another session.
  return {
    ...common,
    ...(profile === "cryptography"
      ? crypto
      : profile === "analysis"
        ? analysis
        : {}),
  };
}
